-- PostgreSQL target schema for the NU-ARB control plane.
-- Foundation only: this migration is NOT wired into the application yet.
-- Do not point the app at PostgreSQL until the data-access adapter and migration runner land.
BEGIN;

CREATE TABLE IF NOT EXISTS schema_migrations (
    version BIGINT PRIMARY KEY,
    applied_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS users (
    id TEXT PRIMARY KEY,
    email TEXT NOT NULL UNIQUE,
    salt BYTEA NOT NULL,
    password_hash BYTEA NOT NULL,
    created_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS sessions (
    token_hash TEXT PRIMARY KEY,
    user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    expires_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS sessions_user_id_idx ON sessions(user_id);

CREATE TABLE IF NOT EXISTS exchange_credentials (
    user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    exchange_id TEXT NOT NULL,
    encrypted_credentials BYTEA NOT NULL,
    auth_mode TEXT NOT NULL,
    state TEXT NOT NULL,
    last_verified TIMESTAMPTZ,
    verification_json JSONB NOT NULL DEFAULT '{}'::jsonb,
    PRIMARY KEY (user_id, exchange_id)
);
CREATE INDEX IF NOT EXISTS exchange_credentials_state_idx ON exchange_credentials(state);

CREATE TABLE IF NOT EXISTS trades (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id TEXT NOT NULL,
    timestamp TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    mode TEXT NOT NULL,
    exchange_a TEXT NOT NULL,
    exchange_b TEXT,
    strategy TEXT NOT NULL,
    path JSONB NOT NULL DEFAULT '[]'::jsonb,
    symbols JSONB NOT NULL DEFAULT '[]'::jsonb,
    requested_quantity DOUBLE PRECISION,
    executed_quantity DOUBLE PRECISION,
    average_fill_price DOUBLE PRECISION,
    fees DOUBLE PRECISION,
    gross_pnl DOUBLE PRECISION,
    slippage DOUBLE PRECISION,
    net_pnl DOUBLE PRECISION NOT NULL,
    latency_ms DOUBLE PRECISION,
    book_age_ms DOUBLE PRECISION,
    execution_status TEXT NOT NULL,
    verification_status TEXT NOT NULL,
    risk_decision TEXT,
    failure_reason TEXT,
    target_before DOUBLE PRECISION,
    target_after DOUBLE PRECISION,
    cumulative_realized_pnl DOUBLE PRECISION NOT NULL
);
CREATE INDEX IF NOT EXISTS trades_session_idx ON trades(session_id, id);

CREATE TABLE IF NOT EXISTS opportunities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id TEXT NOT NULL,
    timestamp TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    mode TEXT NOT NULL,
    strategy TEXT NOT NULL,
    exchange_a TEXT NOT NULL,
    exchange_b TEXT,
    symbol TEXT NOT NULL,
    requested_usd DOUBLE PRECISION NOT NULL,
    expected_net_usd DOUBLE PRECISION NOT NULL,
    worst_case_net_usd DOUBLE PRECISION NOT NULL,
    expected_net_bps DOUBLE PRECISION NOT NULL,
    worst_case_net_bps DOUBLE PRECISION NOT NULL,
    book_age_ms DOUBLE PRECISION NOT NULL,
    decision TEXT NOT NULL,
    rejection_reason TEXT,
    evidence JSONB NOT NULL DEFAULT '{}'::jsonb
);
CREATE INDEX IF NOT EXISTS opportunities_session_idx ON opportunities(session_id, id);

CREATE TABLE IF NOT EXISTS venue_certifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    timestamp TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    session_id TEXT,
    venue TEXT NOT NULL,
    symbol TEXT NOT NULL,
    notional_usd DOUBLE PRECISION NOT NULL,
    live_eligible BOOLEAN NOT NULL,
    reasons JSONB NOT NULL DEFAULT '[]'::jsonb,
    evidence JSONB NOT NULL DEFAULT '{}'::jsonb
);
CREATE INDEX IF NOT EXISTS venue_certifications_venue_idx ON venue_certifications(venue, id);

COMMIT;
