-- Initial durable control-plane and evidence journal schema.
-- Credential material is encrypted BYTEA only; never store plaintext secrets.
CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email TEXT NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS sessions (
    id TEXT PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    token_hash TEXT NOT NULL UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX IF NOT EXISTS sessions_user_expiry_idx ON sessions(user_id, expires_at);
CREATE TABLE IF NOT EXISTS exchange_credentials (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    venue TEXT NOT NULL,
    auth_mode TEXT NOT NULL,
    encrypted_payload BYTEA NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE(user_id, venue)
);
CREATE TABLE IF NOT EXISTS trades (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id TEXT NOT NULL, timestamp TIMESTAMPTZ NOT NULL DEFAULT now(),
    mode TEXT NOT NULL, exchange_a TEXT NOT NULL, exchange_b TEXT, strategy TEXT NOT NULL,
    path JSONB NOT NULL DEFAULT '[]'::jsonb, symbols JSONB NOT NULL DEFAULT '[]'::jsonb,
    requested_quantity DOUBLE PRECISION, executed_quantity DOUBLE PRECISION,
    average_fill_price DOUBLE PRECISION, fees DOUBLE PRECISION, gross_pnl DOUBLE PRECISION,
    slippage DOUBLE PRECISION, net_pnl DOUBLE PRECISION NOT NULL DEFAULT 0,
    latency_ms DOUBLE PRECISION, book_age_ms DOUBLE PRECISION,
    execution_status TEXT NOT NULL, verification_status TEXT NOT NULL,
    risk_decision TEXT, failure_reason TEXT, target_before DOUBLE PRECISION,
    target_after DOUBLE PRECISION, cumulative_realized_pnl DOUBLE PRECISION NOT NULL DEFAULT 0,
    audit_metadata JSONB NOT NULL DEFAULT '{}'::jsonb
);
CREATE INDEX IF NOT EXISTS trades_session_idx ON trades(session_id, id);
CREATE TABLE IF NOT EXISTS opportunities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id TEXT NOT NULL, timestamp TIMESTAMPTZ NOT NULL DEFAULT now(),
    mode TEXT NOT NULL, strategy TEXT NOT NULL, exchange_a TEXT NOT NULL, exchange_b TEXT,
    symbol TEXT NOT NULL, requested_usd DOUBLE PRECISION NOT NULL,
    expected_net_usd DOUBLE PRECISION NOT NULL, worst_case_net_usd DOUBLE PRECISION NOT NULL,
    expected_net_bps DOUBLE PRECISION NOT NULL, worst_case_net_bps DOUBLE PRECISION NOT NULL,
    book_age_ms DOUBLE PRECISION NOT NULL, decision TEXT NOT NULL, rejection_reason TEXT,
    evidence JSONB NOT NULL DEFAULT '{}'::jsonb
);
CREATE INDEX IF NOT EXISTS opportunities_session_idx ON opportunities(session_id, id);
CREATE TABLE IF NOT EXISTS venue_certifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    timestamp TIMESTAMPTZ NOT NULL DEFAULT now(), session_id TEXT, venue TEXT NOT NULL,
    symbol TEXT NOT NULL, notional_usd DOUBLE PRECISION NOT NULL,
    live_eligible BOOLEAN NOT NULL DEFAULT FALSE,
    reasons JSONB NOT NULL DEFAULT '[]'::jsonb, evidence JSONB NOT NULL DEFAULT '{}'::jsonb
);
CREATE INDEX IF NOT EXISTS venue_certifications_venue_idx ON venue_certifications(venue, id);
CREATE TABLE IF NOT EXISTS provider_evidence (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider TEXT NOT NULL, request_type TEXT NOT NULL, observed_at TIMESTAMPTZ NOT NULL,
    status TEXT NOT NULL CHECK (status IN ('ok', 'unavailable', 'stale', 'invalid', 'rate_limited', 'error')),
    latency_ms DOUBLE PRECISION, payload_sha256 TEXT,
    evidence JSONB NOT NULL DEFAULT '{}'::jsonb, error_code TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS provider_evidence_provider_time_idx ON provider_evidence(provider, observed_at DESC);
