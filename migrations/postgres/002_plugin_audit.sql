-- Append-only metadata audit for plugin evidence requests; never persist secrets or raw payloads.
CREATE TABLE IF NOT EXISTS plugin_audit_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider TEXT NOT NULL,
    operation TEXT NOT NULL,
    request_id TEXT NOT NULL,
    scope TEXT,
    outcome TEXT NOT NULL CHECK (outcome IN ('completed', 'denied', 'timeout', 'failed')),
    latency_ms BIGINT NOT NULL CHECK (latency_ms >= 0),
    result_code TEXT NOT NULL,
    payload_sha256 TEXT,
    recorded_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS plugin_audit_provider_time_idx ON plugin_audit_log(provider, recorded_at DESC);
